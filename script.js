// ========== FUNGSI MODAL ==========
// ========== 1. FUNGSI BUKA MODAL ==========
function openModal(packageId) {
    const pkg = packages.find(p => p.id === packageId);
    if (!pkg) return;
    
    // Isi data modal
    document.getElementById('modalImage').src = pkg.image;
    document.getElementById('modalTitle').textContent = pkg.name;
    document.getElementById('modalDescription').textContent = pkg.detail;
    document.getElementById('modalDuration').textContent = pkg.duration;
    document.getElementById('modalPrice').textContent = pkg.price;
    document.getElementById('modalFacilities').textContent = pkg.facilities;
    
    // TAMPILKAN MODAL
    document.getElementById('packageModal').style.display = 'block';
}

// ========== 2. FUNGSI TUTUP MODAL ==========
function closeModal() {
    document.getElementById('packageModal').style.display = 'none';
}

// ========== 3. TUTUP MODAL KLIK DI LUAR ==========
window.onclick = function(event) {
    const modal = document.getElementById('packageModal');
    if (event.target === modal) {
        modal.style.display = 'none';
    }
}

// ========== 4. TUTUP MODAL DENGAN ESC ==========
document.addEventListener('keydown', function(event) {
    if (event.key === 'Escape') {
        const modal = document.getElementById('packageModal');
        if (modal.style.display === 'block') {
            modal.style.display = 'none';
        }
    }
});

// ====== MOBILE MENU TOGGLE ======
function toggleMenu(e) {
    e.preventDefault();
    const menuUl = document.getElementById('navMenu');
    const tombol = document.querySelector('.tombol-menu');
    menuUl.classList.toggle('open');
    tombol.classList.toggle('open');
}

function closeMenu() {
    const menuUl = document.getElementById('navMenu');
    const tombol = document.querySelector('.tombol-menu');
    menuUl.classList.remove('open');
    tombol.classList.remove('open');
}

// Close menu when clicking outside
document.addEventListener('click', function(event) {
    const menu = document.getElementById('navMenu');
    const tombol = document.querySelector('.tombol-menu');
    if (menu && menu.classList.contains('open')) {
        const isClickInside = menu.contains(event.target) || tombol.contains(event.target);
        if (!isClickInside) {
            menu.classList.remove('open');
            tombol.classList.remove('open');
        }
    }
});